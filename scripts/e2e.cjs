const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:4173';
(async () => {
  const b = await chromium.launch({ args: process.env.HTTPS_PROXY ? [`--proxy-server=${process.env.HTTPS_PROXY}`, '--proxy-bypass-list=localhost;127.0.0.1'] : [] });
  const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, ignoreHTTPSErrors: true })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  const log = (k, v) => console.log((v ? 'PASS ' : 'FAIL ') + k);
  await p.goto(base + '/workshops', { waitUntil: 'networkidle' });
  await p.getByRole('button', { name: /^Wet Plate/ }).click();
  await p.waitForTimeout(300);
  log('filter writes URL key', p.url().includes('technique=Wet+Plate'));
  log('document.title reflects filter', (await p.title()).startsWith('Workshops: Wet Plate'));
  const n = await p.locator('.wcard').count(); log(`filtered cards = ${n}`, n > 0 && n < 14);
  await p.reload({ waitUntil: 'networkidle' }); log('filter survives reload', (await p.locator('.wcard').count()) === n);
  await p.goto(base + '/workshops/intro-platinum-weekend', { waitUntil: 'networkidle' });
  const tiers = await p.locator('.tier').count(); log(`all tuition tiers visible (${tiers})`, tiers >= 3);
  await p.getByRole('button', { name: /^Register/ }).click();
  await p.waitForTimeout(500);
  log('cart dialog opens (native dialog, modal)', await p.evaluate(() => document.querySelector('dialog.sheet').open && document.querySelector('dialog.sheet').matches(':modal')));
  log('cart line added', (await p.locator('.line').count()) === 1);
  await p.getByRole('button', { name: 'Continue to checkout' }).click();
  const href = await p.locator('.handoff__list a').first().getAttribute('href');
  log('checkout hands off to live workshop URL', href === 'https://www.penumbrafoundation.org/workshops/intro-platinum-weekend');
  await p.keyboard.press('Escape');
  await p.goto(base + '/penumbra-store', { waitUntil: 'networkidle' });
  const shopN = await p.locator('.pcard').count();
  log(`shop hides sold-out by default (${shopN} cards)`, shopN < 40 && (await p.locator('.pcard.is-soldout').count()) === 0);
  log('shipping is not a product', (await p.locator('.pcard', { hasText: 'Domestic shipping' }).count()) === 0);
  log('cart count persisted in header', (await p.locator('.cartbtn__n').innerText()) === '1');
  await p.keyboard.press('Control+k'); await p.waitForTimeout(300);
  await p.keyboard.type('cyanotype'); await p.waitForTimeout(1500);
  const sr = await p.locator('.search__res li').count(); log(`search returns results (${sr})`, sr > 0);
  await p.keyboard.press('Escape');
  await p.goto(base + '/this-does-not-exist', { waitUntil: 'networkidle' });
  log('404 page renders with search', (await p.locator('.nf__q input').count()) === 1);
  await p.goto(base + '/', { waitUntil: 'networkidle' });
  for (let y = 0; y < 8000; y += 600) { await p.mouse.wheel(0, 600); await p.waitForTimeout(120); }
  const badAlt = await p.$$eval('img', is => is.filter(i => !i.closest('a[aria-label]') && !i.alt || /\.(jpe?g|png)$/i.test(i.alt) || /^IMG_|_\d{3,}/.test(i.alt)).map(i => i.src.slice(-40)));
  log(`no empty/filename alt on home (${badAlt.length})`, badAlt.length === 0 || console.log(badAlt));
  console.log('PAGE ERRORS', JSON.stringify(errs));
  await b.close();
})();
